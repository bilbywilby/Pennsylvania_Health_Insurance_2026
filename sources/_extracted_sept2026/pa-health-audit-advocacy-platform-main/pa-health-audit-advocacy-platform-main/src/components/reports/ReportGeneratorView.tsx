import React, { useState } from 'react';
import { AppLayout } from "@/components/layout/AppLayout";
import { Card, CardContent, CardHeader, CardTitle, CardDescription } from "@/components/ui/card";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Badge } from "@/components/ui/badge";
import { PDFGeneratorUI } from "@/components/PDFGeneratorUI";
import { ReportJSON } from "@/lib/types";
import { FileCode, Upload, ShieldCheck, AlertCircle, RotateCcw } from "lucide-react";
import { toast } from "sonner";
export default function ReportGeneratorView() {
  const [report, setReport] = useState<ReportJSON | null>(null);
  const handleFileChange = (e: React.ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0];
    if (!file) return;
    const reader = new FileReader();
    reader.onload = (event) => {
      try {
        const json = JSON.parse(event.target?.result as string) as ReportJSON;
        if (!json.metadata || !json.blocks) throw new Error("Invalid Format");
        setReport(json);
        toast.success("Forensic JSON Parsed Successfully");
      } catch (err) {
        toast.error("Invalid JSON Report Format");
      }
    };
    reader.readAsText(file);
    e.target.value = '';
  };
  const resetParser = () => {
    setReport(null);
    toast.info("Parser state reset");
  };
  return (
    <AppLayout container>
      <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8">
        <div className="py-8 md:py-10 lg:py-12 space-y-12">
          <header className="flex flex-col md:flex-row md:items-end justify-between gap-6">
            <div className="space-y-2">
              <h1 className="text-4xl font-black flex items-center gap-2 tracking-tight">
                <ShieldCheck className="text-blue-600 h-10 w-10" /> Forensic Report Parser
              </h1>
              <p className="text-muted-foreground italic text-lg max-w-2xl">
                Institutional processing for local health insurance findings. Import findings generated by 
                this platform to authorize and sign official PDF documentation.
              </p>
            </div>
            {report && (
              <Button variant="outline" onClick={resetParser} className="font-bold border-2">
                <RotateCcw className="h-4 w-4 mr-2" /> Reset Session
              </Button>
            )}
          </header>
          <div className="grid grid-cols-1 lg:grid-cols-12 gap-12">
            <div className="lg:col-span-5 space-y-8">
              {!report ? (
                <Card className="border-2 shadow-lg h-full">
                  <CardHeader>
                    <CardTitle className="text-sm font-bold uppercase tracking-widest flex items-center gap-2">
                      <Upload className="h-4 w-4" /> Import Source Data
                    </CardTitle>
                  </CardHeader>
                  <CardContent className="flex flex-col justify-center min-h-[300px]">
                    <div className="space-y-6">
                      <p className="text-sm text-muted-foreground text-center">
                        Upload a valid ReportJSON file from a previous session to restore findings.
                      </p>
                      <div className="flex items-center justify-center w-full">
                        <label className="flex flex-col items-center justify-center w-full h-48 border-4 border-dashed rounded-3xl cursor-pointer bg-slate-50 hover:bg-slate-100 transition-all group">
                          <div className="flex flex-col items-center justify-center pt-5 pb-6">
                            <FileCode className="w-12 h-12 mb-4 text-slate-400 group-hover:text-blue-500 transition-colors" />
                            <p className="text-sm text-slate-500 font-black uppercase tracking-tighter">Click to Select JSON Report</p>
                            <p className="text-xs text-slate-400 mt-1">.json files only</p>
                          </div>
                          <Input type="file" className="hidden" accept=".json" onChange={handleFileChange} />
                        </label>
                      </div>
                    </div>
                  </CardContent>
                </Card>
              ) : (
                <div className="animate-slide-up">
                  <PDFGeneratorUI 
                    reportData={report} 
                    fileName={`${report.metadata.title.replace(/\s+/g, '-')}-Signed.pdf`} 
                    triggerLabel="Authorize & Export Final PDF"
                  />
                </div>
              )}
            </div>
            <div className="lg:col-span-7">
              {!report ? (
                <div className="h-full min-h-[400px] border-4 border-dashed rounded-[3rem] flex flex-col items-center justify-center text-slate-300 bg-slate-50/50">
                  <AlertCircle className="h-16 w-16 mb-4 opacity-10" />
                  <p className="font-black uppercase tracking-widest text-sm opacity-40">Awaiting Forensic JSON Import</p>
                </div>
              ) : (
                <Card className="border-2 shadow-2xl animate-fade-in overflow-hidden h-fit">
                  <CardHeader className="border-b bg-slate-900 text-white">
                    <div className="flex items-center justify-between">
                      <CardTitle className="text-sm font-black uppercase tracking-widest">Metadata Context</CardTitle>
                      <Badge className="bg-blue-600">VALIDATED</Badge>
                    </div>
                  </CardHeader>
                  <CardContent className="p-8 space-y-8 bg-white">
                    <div className="grid grid-cols-1 md:grid-cols-2 gap-8">
                      <div className="space-y-1">
                        <p className="text-[10px] font-bold text-slate-400 uppercase tracking-[0.2em]">Platform Report ID</p>
                        <p className="font-mono text-sm bg-slate-100 p-2 rounded-md border">{report.metadata.reportId}</p>
                      </div>
                      <div className="space-y-1">
                        <p className="text-[10px] font-bold text-slate-400 uppercase tracking-[0.2em]">Forensic Timestamp</p>
                        <p className="font-mono text-sm bg-slate-100 p-2 rounded-md border">{new Date(report.metadata.timestamp).toLocaleString()}</p>
                      </div>
                    </div>
                    <div className="p-6 bg-blue-50 border-2 border-blue-100 rounded-3xl">
                      <div className="flex items-center gap-3 mb-4">
                        <FileCode className="h-5 w-5 text-blue-600" />
                        <p className="text-sm font-black uppercase tracking-widest text-blue-900">Structure Integrity</p>
                      </div>
                      <p className="text-2xl font-black text-blue-700">{report.blocks.length} Renderable Data Blocks</p>
                      <p className="text-xs text-blue-600 mt-2 font-medium">Verified for hospital board adjudication format.</p>
                    </div>
                    <div className="space-y-4">
                      <h3 className="text-xs font-black uppercase text-slate-400 tracking-widest px-1">Raw Content Preview</h3>
                      <div className="space-y-3">
                        {report.blocks.slice(0, 6).map((b, i) => (
                          <div key={i} className="flex gap-4 text-xs font-medium border-l-4 border-slate-200 pl-4 py-2 hover:bg-slate-50 transition-colors rounded-r-md">
                             <span className="text-slate-400 font-mono">[{b.x},{b.y}]</span>
                             <span className="truncate text-slate-700">{b.text}</span>
                          </div>
                        ))}
                      </div>
                    </div>
                  </CardContent>
                </Card>
              )}
            </div>
          </div>
        </div>
      </div>
    </AppLayout>
  );
}